"""Tests for preprocessing modules."""
import pytest

from critbench.evaluation.preprocessing.anonymizer import (
    Anonymizer,
    AnonymizationResult,
    anonymize_content,
    anonymize_transcript,
)


class TestAnonymizer:
    """Tests for anonymization module."""

    def test_anonymizer_init(self):
        anonymizer = Anonymizer()
        assert anonymizer.anonymize_models is True
        assert anonymizer.anonymize_providers is True

    def test_anonymize_model_names(self):
        anonymizer = Anonymizer()
        content = "This response was generated by GPT-4 from OpenAI."

        result = anonymizer.anonymize(content)

        assert isinstance(result, AnonymizationResult)
        assert "GPT-4" not in result.anonymized_content
        assert "OpenAI" not in result.anonymized_content
        assert "Model" in result.anonymized_content or "Provider" in result.anonymized_content

    def test_anonymize_claude_references(self):
        anonymizer = Anonymizer()
        content = "Claude from Anthropic is a helpful AI assistant."

        result = anonymizer.anonymize(content)

        assert "Claude" not in result.anonymized_content
        assert "Anthropic" not in result.anonymized_content

    def test_anonymize_gemini_references(self):
        anonymizer = Anonymizer()
        content = "Gemini by Google provides great responses."

        result = anonymizer.anonymize(content)

        assert "Gemini" not in result.anonymized_content
        assert "Google" not in result.anonymized_content

    def test_consistent_anonymization(self):
        anonymizer = Anonymizer()

        # Same model should get same anonymized ID
        content1 = "GPT-4 is good. GPT-4 is great."
        result = anonymizer.anonymize(content1)

        # Count occurrences of the anonymized label
        anon_label = result.mapping.get("GPT-4") or result.mapping.get("gpt-4")
        assert anon_label is not None
        assert result.anonymized_content.count(anon_label) == 2

    def test_anonymize_versions(self):
        anonymizer = Anonymizer(anonymize_versions=True)
        content = "Model version 20250514 with v1.2.3 update."

        result = anonymizer.anonymize(content)

        assert "20250514" not in result.anonymized_content
        assert "[DATE]" in result.anonymized_content or "[VERSION]" in result.anonymized_content

    def test_anonymize_transcript(self):
        anonymizer = Anonymizer()
        transcript = [
            {"turn": 1, "role": "user", "content": "Hello GPT-4"},
            {"turn": 1, "role": "assistant", "content": "Hello from Claude!"},
        ]

        result, mapping = anonymizer.anonymize_transcript(transcript)

        assert len(result) == 2
        assert "GPT-4" not in result[0]["content"]
        assert "Claude" not in result[1]["content"]
        assert len(mapping) > 0

    def test_shuffle_responses(self):
        anonymizer = Anonymizer(shuffle_order=True, seed=42)
        responses = [
            {"id": 1, "content": "First"},
            {"id": 2, "content": "Second"},
            {"id": 3, "content": "Third"},
        ]

        shuffled, indices = anonymizer.shuffle_responses(responses)

        assert len(shuffled) == 3
        assert len(indices) == 3
        # With seed=42, order should be deterministic but shuffled
        assert [r["id"] for r in shuffled] != [1, 2, 3] or indices != [0, 1, 2]

    def test_no_shuffle_when_disabled(self):
        anonymizer = Anonymizer(shuffle_order=False)
        responses = [{"id": i} for i in range(5)]

        shuffled, indices = anonymizer.shuffle_responses(responses)

        assert indices == [0, 1, 2, 3, 4]

    def test_reset(self):
        anonymizer = Anonymizer()
        anonymizer.anonymize("GPT-4 test")
        assert len(anonymizer._mapping) > 0

        anonymizer.reset()
        assert len(anonymizer._mapping) == 0

    def test_convenience_functions(self):
        # Test anonymize_content
        content = "Claude and GPT-4 are both AI models."
        anon = anonymize_content(content)
        assert "Claude" not in anon
        assert "GPT-4" not in anon

        # Test anonymize_transcript
        transcript = [
            {"turn": 1, "role": "assistant", "content": "From OpenAI GPT"},
        ]
        anon_transcript = anonymize_transcript(transcript)
        assert "OpenAI" not in anon_transcript[0]["content"]

    def test_mapping_reverse(self):
        anonymizer = Anonymizer()
        content = "GPT-4 is great."
        result = anonymizer.anonymize(content)

        # Should be able to reverse the mapping
        for original, anon in result.mapping.items():
            assert anon in result.reverse_mapping
            assert result.reverse_mapping[anon] == original

    def test_redactions_tracked(self):
        anonymizer = Anonymizer()
        content = "Claude from Anthropic with version 20250514"
        result = anonymizer.anonymize(content)

        assert len(result.redactions) > 0
        assert any("Model" in r or "Provider" in r or "Version" in r for r in result.redactions)
